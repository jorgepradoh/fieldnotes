import { describe, expect, it } from "vitest";
import { checkParity, formatReport, parseCargoLock, parsePackageLock } from "./tauriParity";

// Inline, real-shaped fixtures only: `npm test` must never read the real lockfiles.

function npmLock(versions: Record<string, string>, extra: Record<string, unknown> = {}): string {
  const packages: Record<string, unknown> = {
    "": { name: "fieldnotes", version: "0.1.0" },
    "node_modules/marked": { version: "18.0.5", resolved: "https://registry.npmjs.org/marked/-/marked-18.0.5.tgz" },
  };
  for (const [name, version] of Object.entries(versions)) {
    packages[`node_modules/@tauri-apps/${name}`] = {
      version,
      resolved: `https://registry.npmjs.org/@tauri-apps/${name}/-/${name}-${version}.tgz`,
      license: "MIT OR Apache-2.0",
    };
  }
  // After the real entries, so a parser that wrongly accepts them would be the last writer.
  Object.assign(packages, extra);
  return JSON.stringify({ name: "fieldnotes", lockfileVersion: 3, requires: true, packages });
}

function cargoLock(versions: Record<string, string | string[]>): string {
  const blocks = ['# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n'];
  blocks.push('[[package]]\nname = "serde"\nversion = "1.0.228"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n');
  for (const [name, v] of Object.entries(versions)) {
    for (const version of Array.isArray(v) ? v : [v]) {
      blocks.push(
        `[[package]]\nname = "${name}"\nversion = "${version}"\n` +
          `source = "registry+https://github.com/rust-lang/crates.io-index"\n` +
          `checksum = "daf9a5c92e39bdd84f22f6be9230e39d0c4e140345f71ffe6058dca4f71127cf"\n` +
          `dependencies = [\n "serde",\n "tauri-plugin",\n]\n`,
      );
    }
  }
  return blocks.join("\n");
}

const MATCHING_NPM = { api: "2.12.1", "plugin-fs": "2.6.0", "plugin-dialog": "2.8.1", "plugin-store": "2.4.3" };
const MATCHING_CRATES = {
  tauri: "2.12.1",
  "tauri-plugin-fs": "2.6.0",
  "tauri-plugin-dialog": "2.8.1",
  "tauri-plugin-store": "2.4.3",
};

describe("checkParity", () => {
  it("passes when every pair is on the same minor", () => {
    const report = checkParity(npmLock(MATCHING_NPM), cargoLock(MATCHING_CRATES));
    expect(report.errors).toEqual([]);
    expect(report.ok).toBe(true);
    expect(report.rows.map((r) => r.npmPackage)).toEqual([
      "@tauri-apps/api",
      "@tauri-apps/plugin-dialog",
      "@tauri-apps/plugin-fs",
      "@tauri-apps/plugin-store",
    ]);
  });

  it("accepts different patch versions of the same minor", () => {
    const report = checkParity(npmLock(MATCHING_NPM), cargoLock({ ...MATCHING_CRATES, tauri: "2.12.9", "tauri-plugin-fs": "2.6.4" }));
    expect(report.ok).toBe(true);
  });

  it("reports the exact mismatch that came with PR #1's lockfiles", () => {
    const report = checkParity(
      npmLock(MATCHING_NPM),
      cargoLock({ ...MATCHING_CRATES, tauri: "2.11.2", "tauri-plugin-fs": "2.5.1", "tauri-plugin-dialog": "2.7.2" }),
    );
    expect(report.ok).toBe(false);
    expect(report.errors).toHaveLength(3);
    expect(report.errors.join("\n")).toContain("@tauri-apps/api 2.12.1 does not match crate tauri 2.11.2");
    expect(report.errors.join("\n")).toContain("@tauri-apps/plugin-fs 2.6.0 does not match crate tauri-plugin-fs 2.5.1");
    expect(report.errors.join("\n")).toContain("@tauri-apps/plugin-dialog 2.8.1 does not match crate tauri-plugin-dialog 2.7.2");
    expect(report.rows.filter((r) => r.ok).map((r) => r.npmPackage)).toEqual(["@tauri-apps/plugin-store"]);
  });

  it("fails on a different major as well as a different minor", () => {
    expect(checkParity(npmLock({ api: "3.0.0" }), cargoLock({ tauri: "2.12.1" })).ok).toBe(false);
    expect(checkParity(npmLock({ api: "2.13.0" }), cargoLock({ tauri: "2.12.9" })).ok).toBe(false);
  });

  it("does not compare the CLI, which has no crate", () => {
    const report = checkParity(npmLock({ ...MATCHING_NPM, cli: "2.11.2", "cli-linux-x64-gnu": "2.11.2" }), cargoLock(MATCHING_CRATES));
    expect(report.ok).toBe(true);
    expect(report.rows.map((r) => r.npmPackage)).not.toContain("@tauri-apps/cli");
  });

  it("fails when an npm plugin has no crate", () => {
    const report = checkParity(npmLock(MATCHING_NPM), cargoLock({ tauri: "2.12.1", "tauri-plugin-fs": "2.6.0", "tauri-plugin-dialog": "2.8.1" }));
    expect(report.ok).toBe(false);
    expect(report.errors).toEqual([expect.stringContaining('no matching crate "tauri-plugin-store"')]);
  });

  it("fails when a crate appears in two versions rather than guessing which one is linked", () => {
    const report = checkParity(npmLock(MATCHING_NPM), cargoLock({ ...MATCHING_CRATES, "tauri-plugin-fs": ["2.6.0", "2.5.1"] }));
    expect(report.ok).toBe(false);
    expect(report.errors.join("\n")).toContain("several versions");
  });

  it("ignores nested copies of a package, which are not the one the app imports", () => {
    const report = checkParity(
      npmLock(MATCHING_NPM, { "node_modules/somelib/node_modules/@tauri-apps/api": { version: "1.0.0" } }),
      cargoLock(MATCHING_CRATES),
    );
    expect(report.ok).toBe(true);
  });

  it("does not pass vacuously on an empty or unrecognised lockfile", () => {
    // Guard: "found nothing to compare" is a failure, not a success.
    expect(checkParity(npmLock({}), cargoLock({})).ok).toBe(false);
    const noCargo = checkParity(npmLock(MATCHING_NPM), "");
    expect(noCargo.ok).toBe(false);
    expect(noCargo.errors[0]).toBe("Cargo.lock lists no packages.");
    expect(checkParity(npmLock({ "plugin-fs": "2.6.0" }), cargoLock({ "tauri-plugin-fs": "2.6.0" })).errors).toEqual([
      expect.stringContaining("does not contain @tauri-apps/api"),
    ]);
  });

  it("fails on versions it cannot read", () => {
    const report = checkParity(npmLock({ api: "latest" }), cargoLock({ tauri: "2.12.1" }));
    expect(report.ok).toBe(false);
    expect(report.errors.join("\n")).toContain("Cannot read a version");
  });
});

describe("parsing", () => {
  it("rejects input that is not a lockfile, with a message that says which one", () => {
    expect(() => parsePackageLock("not json")).toThrow(/package-lock\.json is not valid JSON/);
    expect(() => parsePackageLock("{}")).toThrow(/no "packages" table/);
    expect(() => parsePackageLock("null")).toThrow(/no "packages" table/);
  });

  it("reads Cargo.lock blocks with CRLF line endings", () => {
    const crlf = cargoLock({ tauri: "2.12.1" }).replace(/\n/g, "\r\n");
    expect(parseCargoLock(crlf).get("tauri")).toEqual(["2.12.1"]);
  });

  it("does not take a version from a dependency line", () => {
    const text = '[[package]]\nname = "tauri"\nversion = "2.12.1"\ndependencies = [\n "serde 1.0.1",\n]\n';
    expect(parseCargoLock(text).get("tauri")).toEqual(["2.12.1"]);
  });
});

describe("formatReport", () => {
  it("names each pair and every problem", () => {
    const report = checkParity(npmLock({ api: "2.12.1" }), cargoLock({ tauri: "2.11.2" }));
    const text = formatReport(report);
    expect(text).toContain("FAIL  @tauri-apps/api 2.12.1  <->  tauri 2.11.2");
    expect(text).toContain("error: @tauri-apps/api 2.12.1 does not match crate tauri 2.11.2");
  });
});
